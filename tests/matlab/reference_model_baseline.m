function reference_model_baseline(model)
% Run the published RM3, OSWEC, or Sphere reference cases and save numeric output.
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
outDir = fullfile(repoRoot, 'matlab-reference-model-output');
if ~isfolder(outDir)
    mkdir(outDir);
end

if any(string(model) == ["RM3_MCR_ARRAY", "RM3_MCR_EXCEL", "RM3_MCR_MAT"])
    run_rm3_mcr_baseline(repoRoot, outDir, string(model));
    return;
end
if string(model) == "RM3_MCR_SEASTATE"
    run_rm3_mcr_seastate_baseline(repoRoot, outDir);
    return;
end

switch string(model)
    case "RM3"
        cases = string(model);
        caseDirs = string(fullfile(repoRoot, 'matlab-ref', 'examples', model));
    case "OSWEC"
        cases = string(model);
        caseDirs = string(fullfile(repoRoot, 'matlab-ref', 'examples', model));
        inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        oldSetting = 'waves.spread = [0.1,0.2,0.7];';
        assert(contains(contents, oldSetting), 'The pinned OSWEC input changed');
        contents = strrep(contents, oldSetting, ...
            sprintf('%s\nwaves.phaseSeed = 1;', oldSetting));
        fid = fopen(inputFile, 'w');
        assert(fid ~= -1, 'Could not seed the pinned OSWEC input');
        fprintf(fid, '%s', contents);
        fclose(fid);
    case "Sphere"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', 'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = ["0m", "1m", "1m-ME", "3m", "5m"];
        caseDirs = fullfile(repoRoot, 'applications', 'Free_Decay', cases);
    case "SPHERE_MPC"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "MPC";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Controls', 'MPC'));
    case "SPHERE_REACTIVE_DDPTO"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "ReactiveWithPTO";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Controls', 'ReactiveWithPTO'));
    case "RM3_DD_PTO"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = "RM3_DD_PTO";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'PTO-Sim', 'RM3', 'RM3_DD_PTO'));
    case {"ELLIPSOID_NLH_REG", "ELLIPSOID_NLH_CIC", ...
            "ELLIPSOID_NLH_ODE45"}
        hydroDir = fullfile(repoRoot, 'applications', 'Nonlinear_Hydro', ...
            'hydroData');
        cd(hydroDir);
        if ~isfile('ellipsoid.h5')
            bemio;
        end
        if string(model) == "ELLIPSOID_NLH_ODE45"
            cases = ["ode45_Regular", "ode45_RegularCIC"];
            caseDirs = fullfile(repoRoot, 'applications', ...
                'Nonlinear_Hydro', 'ode45', ["Regular", "RegularCIC"]);
        else
            if string(model) == "ELLIPSOID_NLH_REG"
                waveDir = "Regular";
            else
                waveDir = "RegularCIC";
            end
            cases = "ode4_" + waveDir;
            caseDirs = string(fullfile(repoRoot, 'applications', ...
                'Nonlinear_Hydro', 'ode4', waveDir));
        end
    case "SPHERE_MEAN_DRIFT"
        hydroDir = fullfile(repoRoot, 'applications', 'Mean_Drift', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "Mean_Drift";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Mean_Drift'));
    case "SPHERE_VARIABLE_MASS"
        hydroDir = fullfile(repoRoot, 'applications', 'Variable_Hydro', ...
            'Variable_Mass', 'hydroData');
        cd(hydroDir);
        if ~isfile('draft9.h5')
            bemio;
        end
        cases = "Variable_Mass";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Variable_Hydro', 'Variable_Mass'));
    case "GBM_BARGE"
        hydroDir = fullfile(repoRoot, 'applications', ...
            'Generalized_Body_Modes', 'hydroData');
        cd(hydroDir);
        if ~isfile('barge.h5')
            bemio;
        end
        cases = "Barge";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Generalized_Body_Modes'));
    case "RM3_B2B"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', 'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = ["B2B_Case1", "B2B_Case2", "B2B_Case3", "B2B_Case4"];
        caseDirs = fullfile(repoRoot, 'applications', ...
            'Body-to-Body_Interactions', cases);
    case "RM3_MOORING_MATRIX"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = "MooringMatrix";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Mooring', 'MooringMatrix'));
    case "RM3_END_STOPS"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = "End_Stops";
        caseDirs = string(fullfile(repoRoot, 'applications', 'End_Stops'));
    case {"RM3_END_STOPS_STEP", "RM3_END_STOPS_STEP_FINE", ...
            "RM3_END_STOPS_STEP_FINER", "RM3_END_STOPS_FULL_FINE", ...
            "RM3_END_STOPS_FULL_FINER"}
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        sourceDir = fullfile(repoRoot, 'applications', 'End_Stops');
        if string(model) == "RM3_END_STOPS_STEP"
            cases = "End_Stops_dt005";
            stepSize = 0.05;
        elseif string(model) == "RM3_END_STOPS_STEP_FINE"
            cases = "End_Stops_dt0025";
            stepSize = 0.025;
        elseif string(model) == "RM3_END_STOPS_STEP_FINER"
            cases = "End_Stops_dt00125";
            stepSize = 0.0125;
        elseif string(model) == "RM3_END_STOPS_FULL_FINE"
            cases = "End_Stops_dt0025_full";
            stepSize = 0.025;
        else
            cases = "End_Stops_dt00125_full";
            stepSize = 0.0125;
        end
        runEndTime = 120;
        if startsWith(string(model), "RM3_END_STOPS_FULL")
            runEndTime = 400;
        end
        caseDirs = string(fullfile(repoRoot, 'applications', cases));
        [copied, copyMessage] = copyfile(sourceDir, caseDirs);
        assert(copied, copyMessage);
        inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        assert(contains(contents, 'simu.dt = 0.1;') && ...
            contains(contents, 'simu.endTime = 400;'), ...
            'The pinned End_Stops time settings changed');
        contents = strrep(contents, 'simu.dt = 0.1;', ...
            sprintf('simu.dt = %.4f;', stepSize));
        contents = strrep(contents, 'simu.endTime = 400;', ...
            sprintf('simu.endTime = %d;', runEndTime));
        fid = fopen(inputFile, 'w');
        assert(fid ~= -1, 'Could not write the End_Stops step input');
        fprintf(fid, '%s', contents);
        fclose(fid);
    case "OSWEC_Nonhydro"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'OSWEC', 'hydroData');
        cd(hydroDir);
        if ~isfile('oswec.h5')
            bemio;
        end
        cases = "Nonhydro";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Nonhydro_Body'));
    case "OSWEC_MULTI_WAVE"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'OSWEC', 'hydroData');
        cd(hydroDir);
        if ~isfile('oswec.h5')
            bemio;
        end
        cases = "Multiple_Wave_Spectra";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Multiple_Wave_Spectra'));
        inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        sourceLines = ["waves(1).direction = 0;", ...
            "waves(2).direction = 90;"];
        seedLines = ["waves(1).phaseSeed = 1;", ...
            "waves(2).phaseSeed = 2;"];
        for iWave = 1:2
            assert(contains(contents, sourceLines(iWave)), ...
                'The pinned multiple-wave input changed');
            contents = strrep(contents, char(sourceLines(iWave)), ...
                sprintf('%s\n%s', char(sourceLines(iWave)), ...
                    char(seedLines(iWave))));
        end
        fid = fopen(inputFile, 'w');
        assert(fid ~= -1, 'Could not seed the multiple-wave input');
        fprintf(fid, '%s', contents);
        fclose(fid);
    case "OSWEC_FULL_DIR"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'OSWEC', 'hydroData');
        cd(hydroDir);
        if ~isfile('oswec.h5')
            bemio;
        end
        cases = "Full_Directional_Waves";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Full_Directional_Waves'));
    case "OSWEC_PASSIVE_YAW"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'OSWEC', 'hydroData');
        cd(hydroDir);
        if ~isfile('oswec.h5')
            bemio;
        end
        cases = ["PassiveYawOFF", "PassiveYawON"];
        caseDirs = fullfile(repoRoot, 'applications', 'Passive_Yaw', cases);
    case {"OSWEC_PASSIVE_YAW_IRR", "OSWEC_PASSIVE_YAW_IRR_CONT"}
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'OSWEC', 'hydroData');
        cd(hydroDir);
        if ~isfile('oswec.h5')
            bemio;
        end
        sourceDir = fullfile(repoRoot, 'applications', 'Passive_Yaw', ...
            'PassiveYawRegression');
        if string(model) == "OSWEC_PASSIVE_YAW_IRR_CONT"
            cases = "PassiveYawRegressionContinuous";
            caseDirs = string(fullfile(repoRoot, 'applications', ...
                'Passive_Yaw', cases));
            [copied, copyMessage] = copyfile(sourceDir, caseDirs);
            assert(copied, copyMessage);
            inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
            contents = fileread(inputFile);
            for iBody = 1:2
                oldSetting = sprintf('body(%d).yaw.threshold = 1;', iBody);
                newSetting = sprintf('body(%d).yaw.threshold = 0;', iBody);
                assert(contains(contents, oldSetting), ...
                    'The pinned passive-yaw threshold changed');
                contents = strrep(contents, oldSetting, newSetting);
            end
            fid = fopen(inputFile, 'w');
            assert(fid ~= -1, 'Could not write the continuous-yaw input');
            fprintf(fid, '%s', contents);
            fclose(fid);
        else
            cases = "PassiveYawRegression";
            caseDirs = string(sourceDir);
        end
    case "RM3_PTO_Extension"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = ["float", "spar"];
        caseDirs = fullfile(repoRoot, 'applications', ...
            'RM3_PTO_Extension', cases);
    case "RM3_Radiation_Options"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = ["constant", "FIR", "state_space", "convolution"];
        caseDirs = repmat(string(fullfile(repoRoot, 'applications', ...
            'Radiation_Force_Options')), size(cases));
    case "RM3_MCR"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', 'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        sourceDir = fullfile(repoRoot, 'applications', 'Multiple_Condition_Runs', 'RM3_MCROPT1');
        cases = strings(1, 8);
        caseDirs = strings(1, 8);
        iCase = 0;
        for damping = [1200000, 2400000]
            for period = [6, 8]
                for height = [1.5, 2.5]
                    iCase = iCase + 1;
                    cases(iCase) = sprintf('H%d_T%d_D%d', ...
                        round(10 * height), period, round(damping / 100000));
                    caseDirs(iCase) = fullfile(repoRoot, 'applications', ...
                        'Multiple_Condition_Runs', 'paired_' + cases(iCase));
                    [copied, copyMessage] = copyfile(sourceDir, caseDirs(iCase));
                    assert(copied, copyMessage);
                    inputFile = fullfile(caseDirs(iCase), 'wecSimInputFile.m');
                    contents = fileread(inputFile);
                    oldSettings = ["waves.height = 1.5:1:2.5;", ...
                        "waves.period = 6:2:8;", ...
                        "pto(1).damping=1200000:1200000:2400000;"];
                    newSettings = ["waves.height = " + string(height) + ";", ...
                        "waves.period = " + string(period) + ";", ...
                        "pto(1).damping=" + string(damping) + ";"];
                    for iSetting = 1:numel(oldSettings)
                        assert(contains(contents, oldSettings(iSetting)), ...
                            'The pinned RM3 MCR input changed');
                        contents = strrep(contents, char(oldSettings(iSetting)), ...
                            char(newSettings(iSetting)));
                    end
                    fid = fopen(inputFile, 'w');
                    assert(fid ~= -1, 'Could not write the RM3 MCR input');
                    fprintf(fid, '%s', contents);
                    fclose(fid);
                end
            end
        end
    case "Sphere_Passive"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', 'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "Passive_P";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Controls', 'Passive (P)'));
    case "Sphere_PTO_Config"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', 'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        sourceDir = fullfile(repoRoot, 'applications', 'Controls', 'Passive (P)');
        caseDir = fullfile(repoRoot, 'applications', 'Controls', 'Passive_Config');
        [copied, copyMessage] = copyfile(sourceDir, caseDir);
        assert(copied, copyMessage);
        inputFile = fullfile(caseDir, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        oldSettings = ["pto(1).stiffness = 0;", "pto(1).damping = 0;", ...
            "pto(1).location = [0 0 0];"];
        newSettings = ["pto(1).stiffness = 50000;", ...
            "pto(1).damping = 100000;", "pto(1).location = [1 0 0];"];
        for iSetting = 1:numel(oldSettings)
            assert(contains(contents, oldSettings(iSetting)), ...
                'The pinned passive-controller input changed');
            contents = strrep(contents, char(oldSettings(iSetting)), ...
                char(newSettings(iSetting)));
        end
        fid = fopen(inputFile, 'w');
        assert(fid ~= -1, 'Could not write the configured PTO input');
        fprintf(fid, '%s', contents);
        fclose(fid);
        cases = "Configured";
        caseDirs = string(caseDir);
    case "Sphere_Reactive_PI"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "Reactive_PI";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Controls', ...
            'Reactive (PI)'));
    case "Sphere_Declutching"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "Declutching";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Controls', ...
            'Declutching'));
    case "Sphere_Latching"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "Latching";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Controls', ...
            'Latching'));
    case "MORISON_FIXED"
        cases = "morisonElement";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Morison_Element', cases));
    otherwise
        error('Unknown reference model: %s', model);
end

for iCase = 1:numel(cases)
    cd(caseDirs(iCase));
    if string(model) == "SPHERE_MPC"
        instrument_sphere_mpc();
    end
    if string(model) == "RM3_Radiation_Options"
        [output, simu] = run_radiation_option(cases(iCase));
    else
        wecSim;
    end
    assert(exist('output', 'var') == 1 && ~isempty(output.bodies), ...
        'The MATLAB case produced no body output');
    if string(model) == "SPHERE_MPC"
        cfg = controller(1).modelPredictiveControl;
        assert(strcmp(simu.solver, 'ode4') && simu.dt == 0.01 && ...
            simu.endTime == 400 && simu.rampTime == 100 && ...
            strcmp(waves.type, 'irregular') && ...
            strcmp(waves.spectrumType, 'JS') && ...
            waves.height == 2.5 && waves.period == 8 && ...
            waves.phaseSeed == 1 && ...
            cfg.maxPTOForce == 2e6 && cfg.maxPTOForceChange == 1.5e6 && ...
            cfg.maxPos == 4 && cfg.maxVel == 3 && ...
            cfg.predictionHorizon == 15 && cfg.dt == 0.5 && ...
            controller(1).MPC == 1, ...
            'The pinned Sphere MPC settings changed');
        assert(exist('controller1_out', 'var') == 1 && ...
            size(controller1_out.signals.values, 2) == 12, ...
            'Sphere MPC controller output is missing');
        writematrix([waves.omega(:), waves.amplitude(:), ...
            waves.dOmega(:), waves.phase(:)], ...
            fullfile(outDir, 'SPHERE_MPC_components.csv'));
        writematrix(waves.waveAmpTime, ...
            fullfile(outDir, 'SPHERE_MPC_wave.csv'));
        setup = controller(1).MPCSetup;
        plant = controller(1).plant;
        if isfield(plant, 'sys_c')
            plant = rmfield(plant, 'sys_c');
        end
        save(fullfile(outDir, 'SPHERE_MPC_setup.mat'), 'setup', 'plant');
        assert(exist('plantOutput', 'var') == 1 && ...
            isa(plantOutput, 'timeseries'), ...
            'Sphere MPC prediction-plant output is missing');
        plantTime = plantOutput.Time(:);
        plantValues = squeeze(plantOutput.Data);
        if size(plantValues, 1) ~= numel(plantTime)
            plantValues = plantValues.';
        end
        assert(size(plantValues, 1) == numel(plantTime) && ...
            size(plantValues, 2) == 3, ...
            'Sphere MPC prediction-plant signal changed');
        writematrix([plantTime, plantValues], ...
            fullfile(outDir, 'SPHERE_MPC_plant_output.csv'));
        export_mpc_trace(outDir, 'SPHERE_MPC_full_state.csv', ...
            mpcFullState, 9);
        export_mpc_trace(outDir, 'SPHERE_MPC_excitation_prediction.csv', ...
            mpcExcitationPrediction, 31);
        export_mpc_trace(outDir, 'SPHERE_MPC_command_rate.csv', ...
            mpcCommandRate, 1);
        export_mpc_trace(outDir, 'SPHERE_MPC_iteration.csv', ...
            mpcIteration, 1);
    end
    if string(model) == "GBM_BARGE"
        assert(exist('Flex_out', 'var') == 1 && isstruct(Flex_out) && ...
            isfield(Flex_out, 'signals') && isfield(Flex_out, 'time'), ...
            'The published flexible-body output is missing');
        save(fullfile(outDir, 'GBM_BARGE_Flex_out.mat'), 'Flex_out');
        writematrix(size(Flex_out.signals.values), fullfile(outDir, ...
            'GBM_BARGE_Flex_out_dimensions.csv'));
        assert(strcmp(simu.solver, 'ode45') && simu.dt == 0.05 && ...
            simu.endTime == 400 && simu.rampTime == 100 && ...
            strcmp(waves.type, 'regular') && waves.height == 2 && ...
            waves.period == 8 && body(1).dof > 6 && ...
            body(1).gbmDOF == body(1).dof - 6 && body(1).flex == 1, ...
            'The pinned generalized-body-mode case changed');
        gbm = body(1).hydroForce.hf1.gbm;
        writematrix(gbm.mass_ff, fullfile(outDir, ...
            'GBM_BARGE_flexible_effective_mass.csv'));
        writematrix(gbm.stiffness, fullfile(outDir, ...
            'GBM_BARGE_flexible_stiffness.csv'));
        writematrix(gbm.damping, fullfile(outDir, ...
            'GBM_BARGE_flexible_damping.csv'));
        writematrix(body(1).hydroForce.hf1.fAddedMass, ...
            fullfile(outDir, 'GBM_BARGE_added_mass.csv'));
        writematrix(body(1).hydroForce.hf1.fDamping, ...
            fullfile(outDir, 'GBM_BARGE_radiation_damping.csv'));
        writematrix([body(1).hydroForce.hf1.fExt.re(:), ...
            body(1).hydroForce.hf1.fExt.im(:)], ...
            fullfile(outDir, 'GBM_BARGE_excitation_coefficients.csv'));
        writematrix(body(1).hydroForce.hf1.linearHydroRestCoef, ...
            fullfile(outDir, 'GBM_BARGE_hydrostatic_stiffness.csv'));
        writematrix([output.wave.time(:), output.wave.elevation(:)], ...
            fullfile(outDir, 'GBM_BARGE_wave.csv'));
        writecell(fieldnames(output.bodies(1)), fullfile(outDir, ...
            'GBM_BARGE_body_fields.txt'));
    end
    if any(string(model) == ["RM3_END_STOPS", "RM3_END_STOPS_STEP", ...
                             "RM3_END_STOPS_STEP_FINE", ...
                             "RM3_END_STOPS_STEP_FINER", ...
                             "RM3_END_STOPS_FULL_FINE", ...
                             "RM3_END_STOPS_FULL_FINER"])
        stops = pto(1).hardStops;
        assert(strcmp(stops.upperLimitSpecify, 'on') && ...
            strcmp(stops.lowerLimitSpecify, 'on') && ...
            stops.upperLimitBound == 0.6 && stops.lowerLimitBound == -0.6 && ...
            stops.upperLimitStiffness == 1e8 && ...
            stops.lowerLimitStiffness == 1e8 && ...
            stops.upperLimitDamping == 0 && stops.lowerLimitDamping == 0 && ...
            stops.upperLimitTransitionRegionWidth == 1e-4 && ...
            stops.lowerLimitTransitionRegionWidth == 1e-4, ...
            'The pinned End_Stops effective hard-stop settings changed');
        writematrix([stops.lowerLimitBound, stops.upperLimitBound, ...
            stops.lowerLimitStiffness, stops.upperLimitStiffness, ...
            stops.lowerLimitDamping, stops.upperLimitDamping, ...
            stops.lowerLimitTransitionRegionWidth, ...
            stops.upperLimitTransitionRegionWidth], ...
            fullfile(outDir, string(model) + "_settings.csv"));
        if any(string(model) == ["RM3_END_STOPS_STEP", ...
                                 "RM3_END_STOPS_STEP_FINE", ...
                                 "RM3_END_STOPS_STEP_FINER", ...
                                 "RM3_END_STOPS_FULL_FINE", ...
                                 "RM3_END_STOPS_FULL_FINER"])
            assert(simu.dt == stepSize && simu.endTime == runEndTime, ...
                'The End_Stops step diagnostic did not use its requested settings');
            writematrix([simu.dt, simu.endTime, simu.rampTime], ...
                fullfile(outDir, string(model) + "_run_settings.csv"));
        end
    end
